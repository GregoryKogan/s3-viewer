// Builds the webview bundle: one JS file, one CSS file, plus index.html.
//
// Deliberately not a framework build: esbuild bundles the ES modules and the two
// real dependencies (highlight.js core + marked) into a single file so the app
// can run from `dist/` with no dev server.

import { build } from "esbuild";
import { mkdir, rm, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dist = path.join(root, "dist");
const watch = process.argv.includes("--watch");
// Readable by default: webview stack traces are worth far more than a few
// kilobytes. Pass `--minify` for a release-sized bundle.
const debug = !process.argv.includes("--minify");

async function run() {
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });

  await build({
    entryPoints: [path.join(root, "src/app.js")],
    outfile: path.join(dist, "app.js"),
    bundle: true,
    format: "esm",
    target: ["safari16", "chrome110", "firefox115"],
    minify: !watch && !debug,
    sourcemap: false,
    keepNames: debug,
    logLevel: "info",
    legalComments: "none",
  });

  await build({
    entryPoints: [path.join(root, "src/style.css")],
    outfile: path.join(dist, "style.css"),
    bundle: true,
    minify: !watch && !debug,
    logLevel: "info",
  });

  // index.html references ./app.js and ./style.css.
  const html = await readFile(path.join(root, "src/index.html"), "utf8");
  await writeFile(path.join(dist, "index.html"), html);

  // Keep the generated bundle out of the way of accidental edits.
  await writeFile(
    path.join(dist, ".gitignore"),
    "# generated by scripts/build-frontend.mjs\n*\n",
  );

  console.log(`frontend built → ${path.relative(root, dist)}/`);
}

if (!existsSync(path.join(root, "node_modules"))) {
  console.error("node_modules is missing — run `pnpm install` first.");
  process.exit(1);
}

await run();

if (watch) {
  console.log("watching is not enabled in this build; re-run the script after edits.");
}
